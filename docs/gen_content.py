"""Generate docs/CONTENT.md from the data-core modules.

Run from the repo root:  PYTHONPATH=. /home/user/.venv/bin/python docs/gen_content.py
"""
from __future__ import annotations

from pathlib import Path

from emberdeep.core.types import WeaponProperty
from emberdeep.data.armor import ARMOR
from emberdeep.data.classes import (
    CLASSES, FEATURES, FEATURE_HOOKS_REFERENCED, FULL_CASTER_SLOTS, HALF_CASTER_SLOTS, INVOCATIONS,
    LAND_CIRCLE_SPELLS, SUBCLASSES, WARLOCK_PACT_SLOTS,
)
from emberdeep.data.items import ITEMS, LOOT_TABLES
from emberdeep.data.races import DRAGON_ANCESTRY, RACE_TRAIT_IDS, RACES
from emberdeep.data.weapons import WEAPONS

OUT = Path(__file__).resolve().parent / "CONTENT.md"
AB = ("STR", "DEX", "CON", "INT", "WIS", "CHA")


def table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def props(w) -> str:
    names = [p.name.lower() for p in WeaponProperty if p and p in w.properties and p.name not in ("RANGED",)]
    return ", ".join(names)


def gp(v: float) -> str:
    return f"{v:g}"


def main() -> None:
    o: list[str] = ["# Emberdeep content reference (data-core)\n",
                    "Generated by `docs/gen_content.py` from `emberdeep/data/*`. SRD 5.1 content (CC-BY-4.0).\n"]

    o.append("\n## Weapons\n")
    rows = [[w.id, w.category.name.lower().replace("_", " "), w.damage + (f" / {w.versatile}" if w.versatile else ""),
             w.damage_type.name.lower(), props(w), f"{w.range_ft[0]}/{w.range_ft[1]}" if w.range_ft[1] else "-",
             w.reach_ft, gp(w.weight), gp(w.cost_gp)] for w in WEAPONS.values()]
    o.append(table(["id", "category", "damage", "type", "properties", "range", "reach", "lb", "gp"], rows))

    o.append("\n## Armor\n")
    rows = [[a.id, a.category.name.lower(), a.base_ac, "-" if a.dex_cap is None else a.dex_cap, a.str_req or "-",
             "yes" if a.stealth_disadvantage else "-", gp(a.weight), gp(a.cost_gp)] for a in ARMOR.values()]
    o.append(table(["id", "category", "AC", "DEX cap", "STR", "stealth dis.", "lb", "gp"], rows))

    o.append("\n## Items\n")
    kinds: dict[str, list] = {}
    for it in ITEMS.values():
        kinds.setdefault(it.kind, []).append(it)
    o.append(f"{len(ITEMS)} items. Counts by kind: " + ", ".join(f"{k} {len(v)}" for k, v in sorted(kinds.items())) + ".\n")
    for title, kind_list in (("Potions", ["potion"]), ("Wands, rings, wearables", ["wand", "ring", "cloak", "amulet"]),
                             ("Consumables and tools", ["consumable", "tool", "light"]),
                             ("Keys and relics", ["key", "relic"])):
        o.append(f"\n### {title}\n")
        rows = []
        for k in kind_list:
            for it in kinds.get(k, []):
                note = it.heal or (f"{it.damage.dice} {it.damage.type.name.lower()}" if it.damage else "")
                if it.charges:
                    note = (note + f" {it.charges} charges").strip()
                if it.effect:
                    note = (note + f" [{it.effect.id}]").strip()
                rows.append([it.id, it.kind, it.rarity, gp(it.value_gp), note])
        o.append(table(["id", "kind", "rarity", "value gp", "notes"], rows))
    o.append("\n### Generated families\n")
    o.append("* `spell_scroll_<spell_id>` for every spell up to 3rd level (cantrip 25 gp, 1st 75, 2nd 150, 3rd 300).\n"
             "* `<weapon>_plus_1/2/3` (every weapon) and `<armor>_plus_1/2` (every armor and `shield`).\n"
             "* `potion_of_<type>_resistance`, `ring_of_<type>_resistance` for the ten non-physical damage types.\n"
             "* Gems (10/50/100/500/1000/5000 gp) and art objects (25/250/750/2500/7500 gp).\n")
    gem_rows = []
    for v in sorted({it.value_gp for it in kinds["gem"]}):
        names = [it.id for it in kinds["gem"] if it.value_gp == v]
        gem_rows.append([gp(v), len(names), ", ".join(names)])
    o.append(table(["gem value", "count", "ids"], gem_rows))

    o.append("\n### Loot tables\n")
    rows = [[t.id, t.draws, t.gold, len(t.entries), t.description] for t in LOOT_TABLES.values()]
    o.append(table(["id", "draws", "gold", "entries", "description"], rows))
    o.append("Entry specs: item id, `gold:<expr>`, `table:<id>`, `nothing`. `roll_loot(table_id, rng, n=1)` returns "
             "`(gold, [item ids])`.\n")

    o.append("\n## Races\n")
    rows = []
    for r in RACES.values():
        bon = ", ".join(f"{AB[int(a)]}+{b}" for a, b in r.ability_bonuses.items())
        rows.append([r.id, r.size.name.lower(), r.speed, bon, r.darkvision_ft or "-", ", ".join(r.traits)])
    o.append(table(["id", "size", "speed", "ability bonuses", "darkvision", "traits"], rows))
    o.append("\n### Draconic ancestry\n")
    rows = [[d.id, d.damage_type.name.lower(), f"{d.length_ft} ft {d.shape.name.lower()}"
             + (f" x {d.width_ft} ft" if d.width_ft else ""), AB[int(d.save)]] for d in DRAGON_ANCESTRY.values()]
    o.append(table(["ancestry", "damage", "breath", "save"], rows))
    o.append("\nRace trait hook ids (`RACE_TRAIT_IDS`): " + ", ".join(f"`{t}`" for t in sorted(RACE_TRAIT_IDS)) + "\n")

    o.append("\n## Classes\n")
    rows = []
    for c in CLASSES.values():
        sc = c.spellcasting
        rows.append([c.id, f"d{c.hit_die}", "/".join(AB[int(a)] for a in c.primary),
                     "/".join(AB[int(a)] for a in c.saving_throws), c.subclass_level, ", ".join(c.subclasses),
                     sc.kind if sc else "-", ", ".join(r.id for r in c.resources) or "-"])
    o.append(table(["class", "hit die", "primary", "saves", "subclass lvl", "subclasses", "casting", "resources"], rows))
    for c in CLASSES.values():
        o.append(f"\n### {c.name}\n")
        o.append(f"{c.description}\n\n")
        o.append(f"Skills: choose {c.skill_choices[0]} of {', '.join(s.name.lower() for s in c.skill_choices[1])}. "
                 f"Armor: {', '.join(a.name.lower() for a in c.armor_proficiencies) or 'none'}. "
                 f"Weapons: {', '.join(c.weapon_proficiencies) or 'none'}.\n\n")
        rows = [[lv, ", ".join(ids)] for lv, ids in sorted(c.features_by_level.items())]
        o.append(table(["level", "features"], rows))
        for sid in c.subclasses:
            s = SUBCLASSES[sid]
            o.append(f"\n**Subclass: {s.name}** (`{s.id}`) - {s.description}\n\n")
            rows = [[lv, ", ".join(ids)] for lv, ids in sorted(s.features_by_level.items())]
            o.append(table(["level", "features"], rows))
            if s.bonus_spells:
                o.append("\nBonus spells: " + "; ".join(f"L{lv}: {', '.join(ss)}" for lv, ss in sorted(s.bonus_spells.items())) + "\n")
            if sid == "land":
                for land, tab in LAND_CIRCLE_SPELLS.items():
                    o.append(f"* {land}: " + "; ".join(f"L{lv}: {', '.join(ss)}" for lv, ss in tab.items()) + "\n")

    o.append("\n## Spellcasting tables (levels 1-5)\n")
    rows = [[lv, *FULL_CASTER_SLOTS[lv][:3], *HALF_CASTER_SLOTS[lv][:2], *WARLOCK_PACT_SLOTS[lv]] for lv in range(1, 6)]
    o.append(table(["level", "full 1st", "full 2nd", "full 3rd", "half 1st", "half 2nd", "pact slots", "pact level"], rows))
    rows = []
    for cid in ("bard", "cleric", "druid", "paladin", "ranger", "sorcerer", "warlock", "wizard"):
        sc = CLASSES[cid].spellcasting
        rows.append([cid, AB[int(sc.ability)], "prepared" if sc.prepared else "known",
                     "/".join(str(sc.cantrips_known[l]) for l in range(1, 6)),
                     "/".join(str(sc.spells_known[l]) for l in range(1, 6)) if sc.spells_known else "ability mod + level",
                     len(sc.spell_list)])
    o.append("\n" + table(["class", "ability", "style", "cantrips L1-5", "known L1-5", "list size"], rows))

    o.append("\n## Feature catalogue\n")
    rows = [[f.id, f.source, f.level, f.kind, f.description] for f in FEATURES.values()]
    o.append(table(["id", "source", "level", "kind", "description"], rows))
    o.append("\n### Eldritch invocations\n")
    rows = [[i, d["level"], d["pact"] or "-"] for i, d in INVOCATIONS.items()]
    o.append(table(["invocation", "min warlock level", "pact"], rows))
    o.append(f"\nFeature hook ids required in `rules/features.py` ({len(FEATURE_HOOKS_REFERENCED)}): "
             + ", ".join(f"`{h}`" for h in sorted(FEATURE_HOOKS_REFERENCED)) + "\n")
    OUT.write_text("\n".join(o))


if __name__ == "__main__":
    main()
